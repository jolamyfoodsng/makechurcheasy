// Writes src/lowerthirds/themeIdIndex.generated.ts — every lower-third theme id and the
// alias → canonical id map, taken from src/lowerthirds/themes.ts.
//
// Start-up code (favourites, the Dock) only needs to canonicalise ids; importing themes.ts
// for that pulled ~420 KB of theme HTML/CSS into the Dock's start-up bundle.
// Re-run after adding, removing or renaming lower-third themes:
//   node scripts/export-lower-third-theme-ids.cjs
// (src/lowerthirds/themeIdIndex.test.ts fails when the file is out of date.)
const fs = require("fs");
const os = require("os");
const path = require("path");
const esbuild = require("esbuild");

const root = path.resolve(__dirname, "..");
const outFile = path.join(os.tmpdir(), `mce-theme-ids-${process.pid}.cjs`);
esbuild.buildSync({
  stdin: {
    contents: 'export { ALL_THEME_IDS, getLowerThirdThemeIdAliasEntries } from "./src/lowerthirds/themes";',
    resolveDir: root,
    loader: "ts",
  },
  bundle: true,
  platform: "node",
  format: "cjs",
  outfile: outFile,
  logLevel: "error",
  define: { "import.meta.env": "{}" },
});
const { ALL_THEME_IDS, getLowerThirdThemeIdAliasEntries } = require(outFile);
fs.unlinkSync(outFile);

const ids = [...new Set(ALL_THEME_IDS)].sort();
const aliases = Object.fromEntries(getLowerThirdThemeIdAliasEntries());
const out = `/**
 * themeIdIndex.generated.ts — GENERATED by scripts/export-lower-third-theme-ids.cjs.
 * Do not edit by hand. Lower-third theme ids and alias → canonical ids from themes.ts.
 */
export const LOWER_THIRD_THEME_IDS: readonly string[] = ${JSON.stringify(ids, null, 0)};

export const LOWER_THIRD_THEME_ID_ALIASES: Readonly<Record<string, string>> = ${JSON.stringify(aliases, null, 0)};
`;
fs.writeFileSync(path.join(root, "src/lowerthirds/themeIdIndex.generated.ts"), out);
console.log(`Wrote ${ids.length} theme ids and ${Object.keys(aliases).length} aliases.`);
