// Bundles src/themes/layout/overlay-entry.ts → public/theme-renderer.js
// for the OBS overlay pages. Run: npm run build:theme-renderer
import { build } from "esbuild";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

await build({
  entryPoints: [path.join(root, "src/themes/layout/overlay-entry.ts")],
  outfile: path.join(root, "public/theme-renderer.js"),
  bundle: true,
  format: "iife",
  target: ["chrome103"], // OBS 28+ browser source (CEF 103)
  minify: true,
  legalComments: "none",
  banner: { js: "/* MakeChurchEasy theme renderer — generated by scripts/build-theme-renderer.mjs, do not edit */" },
});
console.log("theme-renderer.js built");
