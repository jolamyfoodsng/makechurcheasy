export interface NativeIconProps extends SVGProps<SVGSVGElement> {
  size?: number | string;
  absoluteStrokeWidth?: boolean;
}
// Compatibility types for existing components; all glyphs are Fluent SVGs.
export type LucideProps = NativeIconProps;
export type LucideIcon = ReturnType<typeof nativeIcon>;

function nativeIcon(name: string, Regular: FluentIcon, Filled: FluentIcon = Regular) {
  const Icon = forwardRef<SVGSVGElement, NativeIconProps>(function NativeIcon(
    { size = 20, strokeWidth: _strokeWidth, absoluteStrokeWidth: _absoluteStrokeWidth,
      stroke: _stroke, fill, color, className, style, ...props }, ref,
  ) {
    const Glyph = fill && fill !== "none" ? Filled : Regular;
    return <Glyph {...props} ref={ref} primaryFill={color ?? "currentColor"}
      className={["native-icon", className].filter(Boolean).join(" ")}
      style={{ fontSize: size, width: size, height: size, ...style }} />;
  });
  Icon.displayName = name;
  return Icon;
}

