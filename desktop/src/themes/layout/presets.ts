/**
 * Built-in theme presets. Every preset is a plain ThemeLayout, so users can
 * open it in the Theme Editor and change anything. Fonts are ones the overlays
 * already ship locally (public/fonts/google/google-fonts.css), so presets work
 * offline in OBS.
 *
 * Phase 1 ships two presets used to prove the renderer in OBS; the remaining
 * five from the plan land in Phase 3.
 */
import type { LayerAnimation, ThemeLayout } from "./types";

const none: LayerAnimation = { preset: "none", duration: 0, delay: 0, easing: "out-cubic" };
const anim = (preset: LayerAnimation["preset"], duration: number, delay = 0, extra: Partial<LayerAnimation> = {}): LayerAnimation => ({
  preset,
  duration,
  delay,
  easing: "out-expo",
  ...extra,
});

